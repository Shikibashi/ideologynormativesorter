import type {
  VNextGraphRelationType,
  VNextSpecialistRelationCoverageRecord,
} from "../types";

const DOCUMENT =
  "docs/vnext-specialist-architecture-review-2026-08.md" as const;

function edgeId(
  sourceId: string,
  relationType: VNextGraphRelationType,
  targetId: string,
): string {
  return `${sourceId}:${relationType}:${targetId}`;
}

function represented(
  sourceId: string,
  section: string,
  relationType: VNextGraphRelationType,
  targetId: string,
  targetLabel: string,
): VNextSpecialistRelationCoverageRecord {
  return {
    coverageId: edgeId(sourceId, relationType, targetId),
    sourceId,
    sourceRecordId: `${DOCUMENT}:${section}`,
    relationType,
    targetLabel,
    targetId,
    edgeId: edgeId(sourceId, relationType, targetId),
    status: "represented",
    rationale:
      "The approved Specialist family graph names this existing ontology node as a typed relation.",
  };
}

function dispositioned(
  sourceId: string,
  section: string,
  relationType: VNextGraphRelationType,
  targetLabel: string,
  rationale: string,
): VNextSpecialistRelationCoverageRecord {
  return {
    coverageId: `${sourceId}:${relationType}:disposition:${targetLabel}`,
    sourceId,
    sourceRecordId: `${DOCUMENT}:${section}`,
    relationType,
    targetLabel,
    status: "dispositioned",
    rationale,
  };
}

function noTypedRelation(
  sourceId: string,
  section: string,
): VNextSpecialistRelationCoverageRecord {
  return {
    coverageId: `${sourceId}:no-typed-family-relation`,
    sourceId,
    sourceRecordId: `${DOCUMENT}:${section}`,
    status: "no_typed_relation_declared",
    rationale:
      "The approved family-graph column does not declare a typed relation for this row; nearest-neighbor prose is not promoted to a graph edge without a further adjudication.",
  };
}

