import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import type { CanonicalContentBundle } from "../packages/contracts/src/content";
import { buildAssessmentDiagnostics, prepareAssessmentResponses, prepareSpecialistAssessment, scoreConstructLayer, scoreModifiers, scorePrimaryProfiles, scoreSpecialists } from "../packages/engine/src";

const root = process.cwd();
const bundle = JSON.parse(readFileSync(path.join(root, "v2/generated/content.bundle.json"), "utf8")) as CanonicalContentBundle;
const activeItems = bundle.items.filter((item) => item.status === "active");
const responses = activeItems.map((item, index) => {
  if (item.responseType === "statement-choice") return { state: "answered", itemId: item.id, responseType: item.responseType, optionId: item.options[0].id };
  return {
    state: "answered",
    itemId: item.id,
    responseType: item.responseType,
    value: item.responseType === "likert5" ? index % 5 - 2 : index % 7 - 3,
    ...(item.layer === "descriptive" ? { confidence: index % 3 === 0 ? 1 : index % 3 === 1 ? 3 : 5 } : {}),
    ...(item.layer === "prescriptive" ? { priority: index % 3 === 0 ? 1 : index % 3 === 1 ? 3 : 5 } : {}),
  };
});
const constructs = scoreConstructLayer(prepareAssessmentResponses(responses, bundle), bundle);
const profiles = scorePrimaryProfiles(constructs, bundle);
const modifiers = scoreModifiers(constructs, bundle);
const specialistResponses = responses.filter((response) => bundle.items.find((item) => item.id === response.itemId)?.role === "specialist");
const specialistPrepared = prepareSpecialistAssessment({ requestedModuleIds: bundle.specialistModules.map((module) => module.id), responses: specialistResponses }, bundle);
const specialists = scoreSpecialists(constructs, specialistPrepared, bundle);
const diagnostics = buildAssessmentDiagnostics({ bundle, constructs, profiles, modifiers, specialists });
const values = { preparedAssessment: prepareAssessmentResponses(responses, bundle), constructAssessment: constructs, primaryProfileAssessment: profiles, modifierAssessment: modifiers, specialistAssessment: specialists, assessmentDiagnostics: diagnostics };
const sizes = Object.fromEntries(Object.entries(values).map(([key, value]) => [key, Buffer.byteLength(JSON.stringify(value), "utf8")]));
const diagnosticsOverhead = sizes.assessmentDiagnostics - sizes.constructAssessment;
const markdown = `# Phase 8 result-size report\n\nGenerated by \`v2/tools/measure-phase8-result-size.ts\` from a full active-item extensive fixture (${activeItems.length} active items, all specialist modules requested).\n\n| Artifact | UTF-8 JSON bytes |\n| --- | ---: |\n${Object.entries(sizes).map(([key, value]) => `| ${key} | ${value} |`).join("\n")}\n\nDiagnostics-over-construct-assessment bytes: ${diagnosticsOverhead}\n\nThe diagnostic layer stores IDs and structured comparison records; it does not embed item wording or full provenance sources. The size is a measurement for this fixture, not a release limit.\n`;
writeFileSync(path.join(root, "docs/v2/result-size-report.md"), markdown, "utf8");
console.log(JSON.stringify({ sizes, diagnosticsOverhead }, null, 2));
