import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(process.cwd());
const bundle = JSON.parse(readFileSync(resolve(root, "v2/generated/content.bundle.json"), "utf8"));

function ordered(value) {
  if (Array.isArray(value)) return value.map(ordered);
  if (value && typeof value === "object") return Object.fromEntries(Object.entries(value).sort(([left], [right]) => left.localeCompare(right)).map(([key, entry]) => [key, ordered(entry)]));
  return value;
}

function canonical(value) { return JSON.stringify(ordered(value)); }
function digest(value) { return createHash("sha256").update(canonical(value)).digest("hex"); }
function bytes(value) { return Buffer.byteLength(value, "utf8"); }

function response(item) {
  if (item.responseType === "statement-choice") return { state: "answered", itemId: item.id, responseType: item.responseType, optionId: item.options[0].id };
  return { state: "answered", itemId: item.id, responseType: item.responseType, value: item.scaleMin ?? 0 };
}

const coreResponses = bundle.items.filter((item) => item.role === "core" && item.status === "active").map(response);
const specialistResponses = bundle.items.filter((item) => item.role === "specialist" && item.status === "active").map(response);
const privateBase = {
  kind: "private-export",
  saveSchemaVersion: "save-v2.phase12.1",
  contentVersion: bundle.metadata.contentVersion,
  contentFingerprint: bundle.metadata.contentFingerprint,
  responseSchemaVersion: bundle.metadata.responseSchemaVersion,
  scoringVersion: bundle.metadata.scoringVersion,
  session: { stage: "ready-to-score", presentationProgress: { coreIndex: coreResponses.length, specialistModuleIndex: bundle.specialistModules.length, specialistItemIndex: specialistResponses.length } },
  assessmentInput: { responseSchemaVersion: bundle.metadata.responseSchemaVersion, contentFingerprint: bundle.metadata.contentFingerprint, coreResponses, specialistResponses, requestedSpecialistModuleIds: bundle.specialistModules.map((module) => module.id) },
};
const privateEnvelope = { ...privateBase, integrity: { algorithm: "sha256", digest: digest(privateBase) } };

const primaryMatches = bundle.profiles.slice(0, 3).map((profile, index) => ({ profileId: profile.id, name: profile.name, similarity: 0.75 - index * 0.03, rank: index + 1, tieGroup: null, status: "scored" }));
const publicBase = {
  kind: "public-share",
  shareSchemaVersion: "share-v2.phase12.1",
  contentVersion: bundle.metadata.contentVersion,
  scoringVersion: bundle.metadata.scoringVersion,
  resultSchemaVersion: bundle.metadata.resultSchemaVersion,
  primaryMatches,
  primaryTie: { isTie: false, profileIds: [primaryMatches[0].profileId], similarityDelta: 0.03, tolerance: 0.02 },
  modifiers: bundle.modifiers.map((modifier) => ({ modifierId: modifier.id, name: modifier.name, status: "active", fit: 0.72 })),
  specialists: bundle.specialistModules.map((module) => ({ moduleId: module.id, status: "scored", profiles: bundle.specialists.filter((profile) => String(profile.moduleId) === String(module.id)).slice(0, 3).map((profile, index) => ({ profileId: profile.id, name: profile.name, similarity: 0.7 - index * 0.02, rank: index + 1, tieGroup: null, status: "scored" })) })),
  evidenceSummary: { status: "complete", coreCoverage: 1, uncertaintyLevel: "low" },
  methodologyMetadata: { profileLanguage: "similarity", rawResponsesIncluded: false, diagnosticsIncluded: false },
};
const publicShare = { ...publicBase, integrity: { algorithm: "sha256", digest: digest(publicBase) } };
const privateBytes = bytes(canonical(privateEnvelope));
const publicBytes = bytes(canonical(publicShare));
const report = `# Phase 12 Persistence Size Report

This report is generated by v2/tools/measure-persistence-size.mjs from the compiled canonical bundle. The private sample includes every active core and specialist response without a cached result; the public sample includes the full result projection shape.

| Artifact | UTF-8 bytes | Limit | Status |
| --- | ---: | ---: | --- |
| Private save sample | ${privateBytes} | 2097152 | ${privateBytes <= 2097152 ? "PASS" : "FAIL"} |
| Public share sample | ${publicBytes} | 65536 | ${publicBytes <= 65536 ? "PASS" : "FAIL"} |

The sizes are bounded before storage/export. SHA-256 is an integrity check, not an authentication or signature mechanism.
`;
writeFileSync(resolve(root, "docs/v2/persistence-size-report.md"), report);
process.stdout.write(report);
