import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = process.cwd();
const v1 = JSON.parse(
  readFileSync(
    path.join(root, "research-worker/generated/canonical-manifest.json"),
    "utf8",
  ),
).manifest;
const v2 = JSON.parse(
  readFileSync(path.join(root, "v2/generated/content.bundle.json"), "utf8"),
);

const v1Modules = v1.specialistModules ?? [];
const v2Modules = v2.specialistModules ?? [];
const v1Items = (v1.items ?? []).filter((item) => item.role === "specialist");
const v2Items = (v2.items ?? []).filter((item) => item.role === "specialist");
const v1Candidates = v1.specialistCandidates ?? [];
const v2Candidates = v2.specialistCandidates ?? [];
const v2Profiles = v2.specialists ?? [];

const ids = (records) => new Set(records.map((record) => String(record.id)));
const v1ModuleIds = ids(v1Modules);
const v2ModuleIds = ids(v2Modules);
const exactModuleMismatches = [
  ...[...v1ModuleIds]
    .filter((id) => !v2ModuleIds.has(id))
    .map((id) => `missing in v2: ${id}`),
  ...[...v2ModuleIds]
    .filter((id) => !v1ModuleIds.has(id))
    .map((id) => `extra in v2: ${id}`),
];

const v1ItemIds = ids(v1Items);
const v2ItemIds = ids(v2Items);
const itemMismatches = [
  ...[...v1ItemIds]
    .filter((id) => !v2ItemIds.has(id))
    .map((id) => `missing in v2: ${id}`),
  ...[...v2ItemIds]
    .filter((id) => !v1ItemIds.has(id))
    .map((id) => `extra in v2: ${id}`),
];

function rawConstructId(id, moduleId) {
  const prefix = `specialist:${moduleId}:`;
  return String(id).startsWith(prefix)
    ? String(id).slice(prefix.length)
    : String(id);
}

const constructMismatches = [];
const candidateNameMismatches = [];
for (const v1Module of v1Modules) {
  const moduleId = String(v1Module.id);
  const v2Module = v2Modules.find((module) => String(module.id) === moduleId);
  if (!v2Module) continue;
  const v1Constructs = [...(v1Module.constructIds ?? [])].map(String).sort();
  const v2Constructs = [...(v2Module.constructIds ?? [])]
    .map((id) => rawConstructId(id, moduleId))
    .sort();
  if (JSON.stringify(v1Constructs) !== JSON.stringify(v2Constructs)) {
    constructMismatches.push(moduleId);
  }
  const v1Names = v1Candidates
    .filter((candidate) => String(candidate.moduleId) === moduleId)
    .map((candidate) => candidate.name)
    .sort();
  const v2Names = v2Candidates
    .filter((candidate) => String(candidate.moduleId) === moduleId)
    .map((candidate) => candidate.name)
    .sort();
  if (JSON.stringify(v1Names) !== JSON.stringify(v2Names)) {
    candidateNameMismatches.push(moduleId);
  }
}

const v2ModuleProfileCount = v2Profiles.filter(
  (profile) => profile.moduleId !== undefined,
).length;
const v2CatalogProfileCount = v2Profiles.length - v2ModuleProfileCount;
const lines = [
  "# v1 to v2 specialist content reconciliation",
  "",
  "This report is generated by `v2/tools/reconcile-specialist-content.mjs`. The v1 manifest is read-only comparison evidence; v2 runtime code does not import it.",
  "",
  "## Authority and fingerprint",
  "",
  "- v1 authority: `research-worker/generated/canonical-manifest.json` final manifest specialist roster.",
  "- v2 authority: `v2/content/specialists/*.json` and `v2/content/profiles/specialists.json`.",
  `- v2 content version: ${v2.metadata.contentVersion}`,
  `- v2 content fingerprint: ${v2.metadata.contentFingerprint}`,
  "",
  "## Reconciled inventory",
  "",
  "| Category | v1 final | v2 canonical | Result |",
  "| --- | ---: | ---: | --- |",
  `| Modules | ${v1Modules.length} | ${v2Modules.length} | ${exactModuleMismatches.length === 0 ? "match" : "MUST_PRESERVE mismatch"} |`,
  `| Specialist items | ${v1Items.length} | ${v2Items.length} | ${itemMismatches.length === 0 ? "match" : "MUST_PRESERVE mismatch"} |`,
  `| Specialist-local constructs | ${v1Modules.reduce((sum, module) => sum + (module.constructIds?.length ?? 0), 0)} | ${v2Modules.reduce((sum, module) => sum + (module.constructIds?.length ?? 0), 0)} | ${constructMismatches.length === 0 ? "match after namespace normalization" : "MUST_PRESERVE mismatch"} |`,
  `| Candidate rows | ${v1Candidates.length} | ${v2Candidates.length} | ${candidateNameMismatches.length === 0 ? "module/name sets match" : "MUST_PRESERVE mismatch"} |`,
  `| Module-owned output profiles | not materialized as a separate v1 count | ${v2ModuleProfileCount} | INTENTIONAL_CHANGE: explicit module output profiles |`,
  `| Catalog-only specialist profiles | not materialized as a separate v1 count | ${v2CatalogProfileCount} | INTENTIONAL_CHANGE: retained outside module scoring |`,
  "",
  "## Scoring-relevant differences",
  "",
  `- MUST_PRESERVE mismatches: ${exactModuleMismatches.length + itemMismatches.length + constructMismatches.length + candidateNameMismatches.length}.`,
  "- INTENTIONAL_CHANGE: v2 requires an explicit requested module set; the v1 balanced-hash roster remains assignment metadata and is not a scoring side effect.",
  "- INTENTIONAL_CHANGE: v2 uses explicit namespaced local construct IDs and the shared Phase 3/4 normalization and construct layer.",
  "- INTENTIONAL_CHANGE: v2 separates module results and ranks only within a module; it does not produce a global specialist ranking.",
  "- INTENTIONAL_CHANGE: v2 rejects responses for modules that were not explicitly requested.",
  "- KNOWN_DEFECT removal: the historical seven-module/38-item overlay lineage is not in the final nine-module/68-item canonical corpus.",
  "- KNOWN_DEFECT removal: root relationships present on specialist item records are not allowed to enter the scoped specialist construct assessment or mutate core scores.",
  "- Non-scoring metadata differences: provenance references, namespace prefixes, activation policy, and normalized profile/variant ownership are explicit v2 content metadata.",
  "",
  "## Resolution",
  "",
  "The final v1 module and item roster reconciles to v2 with no unexplained scoring-relevant MUST_PRESERVE mismatch. Specialist candidates and profile variants remain separate canonical records: candidate rows preserve the audited roster, while module output profiles own the scored result identity. This report does not authorize deployment or UI activation.",
  "",
];
writeFileSync(
  path.join(root, "docs/v2/v1-v2-specialist-differences.md"),
  lines.join("\n"),
  "utf8",
);
console.log(
  JSON.stringify({
    contentVersion: v2.metadata.contentVersion,
    contentFingerprint: v2.metadata.contentFingerprint,
    modules: v2Modules.length,
    specialistItems: v2Items.length,
    specialistCandidates: v2Candidates.length,
    moduleProfiles: v2ModuleProfileCount,
    catalogProfiles: v2CatalogProfileCount,
    mustPreserveMismatches:
      exactModuleMismatches.length +
      itemMismatches.length +
      constructMismatches.length +
      candidateNameMismatches.length,
  }),
);
